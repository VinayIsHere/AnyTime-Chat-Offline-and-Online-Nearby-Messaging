// core/domain/Identifiers.h
//
// PeerId and the strongly-typed row identifiers.
//
// AD-05: identity is a keypair, never a username. PeerId is the first 8 bytes of
// the SHA-256 fingerprint of the Curve25519 static public key. Usernames are
// display labels and may collide, because with no server there is no registry to
// make them unique.

#pragma once

#include <array>
#include <functional>
#include <optional>
#include <string>

#include "core/domain/Primitives.h"
#include "core/domain/constants/CryptoConstants.h"

namespace anytime {

using PeerIdBytes = std::array<Byte, kPeerIdBytes>;
using PublicKey   = std::array<Byte, kPublicKeyBytes>;
using Signature   = std::array<Byte, kSignatureBytes>;

class PeerId {
public:
    PeerId() = default;
    explicit PeerId(const PeerIdBytes& bytes) : bytes_(bytes) {}

    /// Truncates a full key fingerprint to the wire identity.
    static PeerId fromFingerprint(ByteSpan fingerprint);

    /// Parses 16 hex characters. Returns nullopt on malformed input.
    static std::optional<PeerId> fromHex(const std::string& hex);

    const PeerIdBytes& bytes()  const noexcept { return bytes_; }
    bool               isNull() const noexcept;

    /// Full 16-character lowercase hex — the wire and database form.
    std::string toHex() const;

    /// Last 4 hex characters, for disambiguating colliding usernames in the UI
    /// (the "4f2a" in "@vinay·4f2a").
    ///
    /// DISPLAY ONLY. See kShortLabelChars in constants/CryptoConstants.h for why
    /// this must never be treated as verification.
    std::string shortLabel() const;

    friend bool operator==(const PeerId& a, const PeerId& b) noexcept {
        return a.bytes_ == b.bytes_;
    }
    friend bool operator!=(const PeerId& a, const PeerId& b) noexcept { return !(a == b); }
    friend bool operator<(const PeerId& a, const PeerId& b) noexcept {
        return a.bytes_ < b.bytes_;
    }

private:
    PeerIdBytes bytes_{};
};

// ── Row identifiers ──────────────────────────────────────────────────────────

struct ChatIdTag;
struct MessageIdTag;
struct RequestIdTag;
struct ClientMessageIdTag;

using ChatId    = TaggedId<ChatIdTag>;
using MessageId = TaggedId<MessageIdTag>;
using RequestId = TaggedId<RequestIdTag>;

/// Generated by the UI so an optimistic bubble can be reconciled with the stored
/// row once the core assigns a real MessageId.
using ClientMessageId = TaggedId<ClientMessageIdTag>;

/// Identifies one open link on one transport. Scoped to the transport that
/// issued it — never compare LinkIds across transports.
using LinkId = std::uint32_t;
inline constexpr LinkId kInvalidLink = 0;

/// Opaque handle for a scheduled callback, so it can be cancelled.
using TimerId = std::uint64_t;
inline constexpr TimerId kInvalidTimer = 0;

/// Opaque paging cursor. Implementation-defined; the UI round-trips it verbatim.
using Cursor = std::string;

}  // namespace anytime

// std::hash so PeerId and the tagged ids work as unordered_map keys.
namespace std {

template <>
struct hash<anytime::PeerId> {
    std::size_t operator()(const anytime::PeerId& id) const noexcept;
};

template <typename Tag>
struct hash<anytime::TaggedId<Tag>> {
    std::size_t operator()(const anytime::TaggedId<Tag>& id) const noexcept {
        return std::hash<std::string>{}(id.value());
    }
};

}  // namespace std
